let actual = 'es';

/** Idioma del navegador si está soportado; español si no. */
export function detectarIdioma(lenguajes = []) {
  for (const l of lenguajes) {
    const corto = String(l).slice(0, 2).toLowerCase();
    if (IDIOMAS.includes(corto)) return corto;
  }
  return 'es';
}

export function fijarIdioma(idioma) {
  if (IDIOMAS.includes(idioma)) actual = idioma;
  return actual;
}

export const idiomaActual = () => actual;

/** Devuelve el texto de `clave` con {variables} sustituidas; si falta, devuelve la clave. */
export function t(clave, vars = {}) {
  const base = TEXTOS[actual][clave] ?? TEXTOS.es[clave] ?? clave;
  return base.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
